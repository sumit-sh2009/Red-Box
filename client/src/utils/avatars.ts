// Helper to convert a matrix sprite to an SVG string
export function renderSpriteSvg(sprite: PixelSprite, size: number = 48): string {
  const height = sprite.matrix.length;
  const width = sprite.matrix[0].length;

  let rects = '';
  for (let y = 0; y < height; y++) {
    const row = sprite.matrix[y];
    for (let x = 0; x < width; x++) {
      const char = row[x];
      if (char !== '.') {
        const colorIndex = parseInt(char, 10);
        const color = sprite.colors[colorIndex] || '#000000';
        rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${color}" shape-rendering="crispEdges" />`;
      }
    }
  }

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${size}" height="${size}" style="image-rendering: pixelated; shape-rendering: crispEdges;">${rects}</svg>`;
}

export function getAvatarById(id: string): PixelSprite {
  const found = AVATAR_PRESETS.find((a) => a.id === id);
  return found || AVATAR_PRESETS[0];
}
